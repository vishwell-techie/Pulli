#!/usr/bin/env python3
"""mkfont.py — regenerate runtime/font.c from runtime/font.txt.

    python3 tools/mkfont.py            rewrite runtime/font.c
    python3 tools/mkfont.py --check    exit 1 if font.c is out of date

font.txt is the source of truth and font.c is committed, so building the
runtime never needs Python.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from refgfx import load_font   # noqa: E402

OUT = os.path.join(HERE, "..", "runtime", "font.c")


def render():
    lines = ["/* Generated by tools/mkfont.py from runtime/font.txt. Do not edit. */",
             '#include "pulli.h"', "",
             "const uint8_t pulli_font8x8[96 * 8] = {"]
    for i, rows in enumerate(load_font()):
        code = 32 + i
        label = chr(code) if 32 < code < 127 and chr(code) != "\\" else f"{code}"
        lines.append("    " + ",".join(f"0x{r:02X}" for r in rows) + f",  /* {label} */")
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print("runtime/font.c is out of date: run python3 tools/mkfont.py")
            return 1
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote runtime/font.c")
    return 0


if __name__ == "__main__":
    sys.exit(main())
