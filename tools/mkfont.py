#!/usr/bin/env python3
"""mkfont.py — regenerate runtime/font.c, runtime/font_ta.c and
runtime/font_ta_small.c from the fonts' text files: runtime/font.txt
(English and the button icons), runtime/font_ta.txt (Tamil) and
runtime/font_ta_small.txt (Tamil, the small size).

    python3 tools/mkfont.py            rewrite the .c files
    python3 tools/mkfont.py --check    exit 1 if any is out of date

The .txt files are the source of truth and the .c files are committed, so
building the runtime never needs Python.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from refgfx import load_font, load_icons, ICON_NAMES, TamilFont   # noqa: E402

RUNTIME = os.path.join(HERE, "..", "runtime")
OUT = os.path.join(RUNTIME, "font.c")
TAMIL = [("font_ta", "pulli_font_ta"), ("font_ta_small", "pulli_font_ta_small")]


def render():
    lines = ["/* Generated by tools/mkfont.py from runtime/font.txt. Do not edit. */",
             '#include "pulli.h"', "",
             "const uint8_t pulli_font8x8[96 * 8] = {"]
    for i, rows in enumerate(load_font()):
        code = 32 + i
        label = chr(code) if 32 < code < 127 and chr(code) != "\\" else f"{code}"
        lines.append("    " + ",".join(f"0x{r:02X}" for r in rows) + f",  /* {label} */")
    lines += ["};", ""]
    # The button icons, U+E000 onwards, 8 rows each, (width + 7) / 8 bytes a row.
    widths, offsets, bits = [], [], []
    for width, rows in load_icons():
        widths.append(width)
        offsets.append(len(bits))
        for row in rows:
            row = row + "." * (-len(row) % 8)
            bits += [int(row[i:i + 8].replace(".", "0").replace("#", "1"), 2) for i in range(0, len(row), 8)]
    lines += [f"/* {', '.join(ICON_NAMES)} */",
              f"const uint8_t pulli_font_icon_width[PULLI_ICON_COUNT] = {{ {', '.join(map(str, widths))} }};",
              f"const uint16_t pulli_font_icon_offset[PULLI_ICON_COUNT] = {{ {', '.join(map(str, offsets))} }};",
              "const uint8_t pulli_font_icon_bits[] = {"]
    for i in range(0, len(bits), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in bits[i:i + 16]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def render_ta(base, symbol):
    ta = TamilFont(os.path.join(RUNTIME, base + ".txt"))
    # Sorted by their letters, padded with zeros, for the runtime's binary search.
    order = sorted(ta.glyphs, key=lambda name: [ord(ch) for ch in name] + [0] * (4 - len(name)))
    table, bits = [], []
    for name in order:
        width, kern, adv, rows = ta.glyphs[name]
        letters = [ord(ch) for ch in name] + [0] * (4 - len(name))
        offset = len(bits)
        for row in rows:
            row = row + "." * (-len(row) % 8)
            bits += [int(row[i:i + 8].replace(".", "0").replace("#", "1"), 2) for i in range(0, len(row), 8)]
        table.append(f"    {{ {{{', '.join(f'0x{c:04X}' for c in letters)}}}, {width}, {kern}, {adv}, {offset} }},"
                     f"  /* {' '.join(f'U+{ord(ch):04X}' for ch in name)} */")
    lines = [f"/* Generated by tools/mkfont.py from runtime/{base}.txt. Do not edit.",
             " * Made from Noto Sans Tamil, Copyright 2022 The Noto Project Authors,",
             " * licensed under the SIL Open Font License 1.1: third_party/noto-sans-tamil/OFL.txt. */",
             '#include "pulli.h"', "",
             "static const pulli_ta_glyph glyphs[] = {"] + table + ["};", "",
             "static const uint8_t bits[] = {"]
    for i in range(0, len(bits), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in bits[i:i + 16]) + ",")
    lines += ["};", "",
              f"const pulli_ta_font {symbol} = {{ glyphs, bits, {len(order)}, {ta.rows}, {ta.above} }};", ""]
    return "\n".join(lines)


def main():
    outputs = [(OUT, render())] + [(os.path.join(RUNTIME, base + ".c"), render_ta(base, symbol))
                                   for base, symbol in TAMIL]
    if "--check" in sys.argv:
        stale = [path for path, text in outputs
                 if (open(path).read() if os.path.exists(path) else "") != text]
        for path in stale:
            print(f"runtime/{os.path.basename(path)} is out of date: run python3 tools/mkfont.py")
        return 1 if stale else 0
    for path, text in outputs:
        with open(path, "w") as f:
            f.write(text)
        print(f"wrote runtime/{os.path.basename(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
