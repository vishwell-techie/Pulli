// The status line's message in the language in use.
export function say(text, to = lang) {
  if (to !== "ta" || typeof text !== "string") return text;
  if (TA[text]) return TA[text];
  for (const [re, ta] of STATUS) if (re.test(text)) return text.replace(re, ta);
  return text;
}
